"""DLL runtime glue shaders (mlof2_runtime.h): GLSL -> SPIR-V -> C headers
  shaders/mlof2_input_prep.comp  -> mlof2_input_prep_spv.h  (g_mlof2_input_prep_spv, size in bytes)
  shaders/mlof2_output_prep.comp -> mlof2_output_prep_spv.h (g_mlof2_output_prep_spv)
Vulkan SDK found like build_mlof2_shaders.py (VULKAN_SDK, PATH, C:\\VulkanSDK\\*)."""
import os, shutil, subprocess, sys, tempfile

D = os.path.dirname(os.path.abspath(__file__))


def glslang():
    sdk = os.environ.get("VULKAN_SDK", "")
    for b in (os.path.join(sdk, "Bin"), os.path.join(sdk, "bin")) if sdk else ():
        if os.path.isfile(os.path.join(b, "glslangValidator.exe")):
            return os.path.join(b, "glslangValidator.exe")
    w = shutil.which("glslangValidator.exe") or shutil.which("glslangValidator")
    if w:
        return w
    if os.path.isdir(r"C:\VulkanSDK"):
        for v in sorted(os.listdir(r"C:\VulkanSDK"), reverse=True):
            c = os.path.join(r"C:\VulkanSDK", v, "Bin", "glslangValidator.exe")
            if os.path.isfile(c):
                return c
    sys.exit("glslangValidator not found")


gv = glslang()
for name in ("mlof2_input_prep", "mlof2_output_prep", "mlof2_glue"):
    src = os.path.join(D, "shaders", name + ".comp")
    with tempfile.TemporaryDirectory() as td:
        spv = os.path.join(td, name + ".spv")
        r = subprocess.run([gv, "-V", "--target-env", "vulkan1.2", src, "-o", spv], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"{name}: {r.stdout}{r.stderr}")
        data = open(spv, "rb").read()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    rows = [", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    out = os.path.join(D, name + "_spv.h")
    with open(out, "w", newline="\n") as f:
        f.write(f"#pragma once\n#include <stdint.h>\n// generated by build_prep_shaders.py from shaders/{name}.comp -- do not edit\n")
        f.write(f"static const size_t g_{name}_spv_size = {len(data)};\n")
        f.write(f"static const uint32_t g_{name}_spv[] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
    print(f"{name}: {len(data)} B -> {out}")
