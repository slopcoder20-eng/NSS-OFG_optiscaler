"""Embed the MLOF2 weight blobs for the DLL runtime (mlof2_runtime.h includes mlof2_blobs.h).
The file of each graph is the blob_name its generated header declares, so the embedded weights always match the graph
the runtime is built with (2026-10-27: a hand-made mlof2_blobs.h had embedded the stale pre-int8 mlof2_{enc,pair,gen}.bin).
  python gen_mlof2_blobs.py [graph dir=generated_cut3_v2_int8] [out=mlof2_blobs.h]"""
import os
import re
import sys

D = os.path.dirname(os.path.abspath(__file__))
gdir = os.path.join(D, sys.argv[1] if len(sys.argv) > 1 else "generated_cut3_v2_int8")
out = os.path.join(D, sys.argv[2] if len(sys.argv) > 2 else "mlof2_blobs.h")
GRAPHS = ("enc", "pair", "gen", "gen_prep", "gen_t")                                                       
                                                                                                                             
EXTRA = (
    ("light_enc", "generated_dp4a_light_v2", "mlof2_light_enc_graph.h"),
    ("light_pair", "generated_dp4a_light_v2", "mlof2_light_pair_graph.h"),
    ("oft_half", "generated_oft_half_v2_int8", "mlof2_oft_half_graph.h"),
    ("oft", "generated_oft_v2_int8", "mlof2_oft_graph.h"),
    ("fuse", "generated_fuse_v2_int8", "mlof2_fuse_graph.h"),
    ("rec8_nol4_pair", "generated_rec8_nol4_v2_int8", "mlof2_pair_int8_graph.h"),
)

lines = ["// Autogenerated MLOF2 weight blobs (gen_mlof2_blobs.py) -- do not edit", "#pragma once", "#include <stdint.h>",
         "#include <stddef.h>", ""]
                                                                                                                
ofdir = os.path.join(D, os.environ["MLOF2_OF_DIR"]) if os.environ.get("MLOF2_OF_DIR") else gdir
for g, gd, hname in [(g, ofdir if g in ("enc", "pair") else gdir, f"mlof2_{g}_int8_graph.h") for g in GRAPHS] + [(c, os.path.join(D, d), h) for c, d, h in EXTRA]:
    hdr = open(os.path.join(gd, hname)).read()
    m = re.search(r'"(mlof2_[a-z_0-9]+\.bin)"', hdr)
    if not m:
        sys.exit(f"no blob_name in mlof2_{g}_int8_graph.h")
    blob = open(os.path.join(gd, m.group(1)), "rb").read()
    words = re.search(r"BLOB_WORDS = (\d+)u", hdr)
    if words and int(words.group(1)) * 4 != len(blob):
        sys.exit(f"{m.group(1)}: {len(blob)} B, but the graph header declares {int(words.group(1)) * 4} B")
    lines.append(f"// {os.path.basename(gd)}/{m.group(1)}: {len(blob)} bytes")
    lines.append(f"alignas(64) static const uint8_t mlof2_{g}_blob[] = {{")
    for i in range(0, len(blob), 32):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 32]) + ",")
    lines.append("};")
    lines.append(f"static const size_t mlof2_{g}_blob_size = sizeof(mlof2_{g}_blob);")
    lines.append("")
    print(f"{g:9s} <- {m.group(1)} ({len(blob)} B)")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote", out)
